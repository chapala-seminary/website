INSERT INTO course_completions (student_id, code, completed_at, track)
  SELECT c.student_id, m.new, c.completed_at,
         CASE WHEN CASE m.level WHEN 'mdiv' THEN 2 WHEN 'thm' THEN 2 WHEN 'assoc' THEN 1 WHEN 'cert' THEN 0 ELSE -1 END > CASE c.track WHEN 'mdiv' THEN 2 WHEN 'thm' THEN 2 WHEN 'assoc' THEN 1 WHEN 'cert' THEN 0 ELSE -1 END THEN m.level ELSE c.track END
  FROM course_completions c JOIN _code_map m ON m.old = c.code
  WHERE true
  ON CONFLICT(student_id, code) DO UPDATE SET
    completed_at = MIN(course_completions.completed_at, excluded.completed_at),
    track = CASE WHEN CASE excluded.track WHEN 'mdiv' THEN 2 WHEN 'thm' THEN 2 WHEN 'assoc' THEN 1 WHEN 'cert' THEN 0 ELSE -1 END > CASE course_completions.track WHEN 'mdiv' THEN 2 WHEN 'thm' THEN 2 WHEN 'assoc' THEN 1 WHEN 'cert' THEN 0 ELSE -1 END
                 THEN excluded.track ELSE course_completions.track END;

