/* Interface words for a language that is not written into the layouts
 * (src/lib/languages.mjs DICTIONARY_LANGUAGES): Swahili first.
 *
 * src/data/interface/<lang>.json holds the English wording of buttons,
 * labels, notices and engine messages, each with its translation. The same
 * lookup runs twice:
 *   - at build time (tools/language-pages.mjs) on the page frame, the
 *     registration card, the exam labels and other interface text that a
 *     layout wrote in English only;
 *   - in the browser (/assets/js/cts-ui-<lang>.js, written by the build) for
 *     the messages the engines put together while a student works.
 * Course text (lessons, questions, answers) is never looked up here; it comes
 * from the lesson and question files.
 *
 * How a key matches. Whitespace is collapsed. A number in the English is a
 * slot: "Unit 3" matches the key "Unit {0}", and the Swahili "Kipindi {0}"
 * gets the same number back. Any key with {0}, {1} ... is also a pattern for
 * other text (a name, an answer letter): "Correct answer: {0}" matches
 * "Correct answer: B". A slot that is itself interface text is translated in
 * turn. A miss returns null, and the caller keeps the English.
 *
 * makeTranslator is written in plain ES5 because its source is copied into
 * the browser script as it stands.
 */
export function makeTranslator(dict) {
  var exact = {}, patterns = [];
  var norm = function (s) { return String(s).replace(/\s+/g, ' ').trim(); };
  var esc = function (s) { return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); };
  Object.keys(dict).forEach(function (key) {
    if (key.charAt(0) === '@') return;
    var k = norm(key);
    exact[k] = dict[key];
    if (/\{\d\}/.test(k)) {
      var order = [];
      var source = esc(k).replace(/\\\{(\d)\\\}/g, function (_m, n) { order.push(Number(n)); return '\u0000'; });
      patterns.push({ strict: new RegExp('^' + source.replace(/\u0000/g, '([^;]+?)') + '$'),
        loose: new RegExp('^' + source.replace(/\u0000/g, '([\\s\\S]+?)') + '$'),
        order: order, value: dict[key], fixed: k.replace(/\{\d\}/g, '').length });
    }
  });
  // Longer fixed text first: "Unit {0} passed" before "Unit {0}".
  patterns.sort(function (a, b) { return b.fixed - a.fixed; });
  var fill = function (value, slots) {
    return value.replace(/\{(\d)\}/g, function (_m, n) { return slots[Number(n)] == null ? '' : slots[Number(n)]; });
  };
  function t(english, depth) {
    if (english == null) return null;
    var text = norm(english);
    if (!text) return null;
    if (Object.prototype.hasOwnProperty.call(exact, text)) return exact[text];
    var nums = [], i = 0;
    var numbered = text.replace(/\d+(?:[.,]\d+)?/g, function (d) { nums.push(d); return '{' + (i++) + '}'; });
    if (i && i < 10 && Object.prototype.hasOwnProperty.call(exact, numbered)) return fill(exact[numbered], nums);
    if ((depth || 0) > 3) return null;
    var usePattern = function (pattern, m) {
      var slots = [];
      pattern.order.forEach(function (n, j) {
        var part = m[j + 1], lead = /^[\s—;:,]*/.exec(part)[0], body = part.slice(lead.length);
        var inner = /[A-Za-z]{3}/.test(body) ? t(body, (depth || 0) + 1) : null;
        slots[n] = inner == null ? part : lead + inner;
      });
      return fill(pattern.value, slots);
    };
    // A slot does not run across "; " ...
    var p, m;
    for (p = 0; p < patterns.length; p++) if ((m = patterns[p].strict.exec(text))) return usePattern(patterns[p], m);
    // ... "A; B" and "A — B" are translated part by part (the engines join reasons so) ...
    var parts = text.split(/(; | — )/);
    if (parts.length > 1) {
      var out = '', whole = true;
      for (var q = 0; q < parts.length && whole; q++) {
        if (q % 2) { out += parts[q]; continue; }
        if (!parts[q]) continue;
        var r = t(parts[q], (depth || 0) + 1);
        if (r == null) whole = false; else out += r;
      }
      if (whole) return out;
    }
    // ... and only then may a slot take a longer run.
    for (p = 0; p < patterns.length; p++) if ((m = patterns[p].loose.exec(text))) return usePattern(patterns[p], m);
    return null;
  }
  return function (english) { return t(english, 0); };
}

/* The browser script for one language: the translator and its dictionary.
   window.CTSUI.t(english, lang) returns the translation or null. */
export function browserScript(lang, dict) {
  const data = JSON.stringify(dict).replace(/</g, '\\u003c');
  return `/* Generated by tools/language-pages.mjs from src/data/interface/${lang}.json. Do not edit. */
(function () {
  var makeTranslator = ${makeTranslator.toString()};
  var t = makeTranslator(${data});
  var previous = window.CTSUI;
  window.CTSUI = { t: function (english, lang) {
    if (lang === ${JSON.stringify(lang)}) return t(english);
    return previous ? previous.t(english, lang) : null;
  } };
})();
`;
}
